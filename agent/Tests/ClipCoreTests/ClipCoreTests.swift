import XCTest
@testable import ClipCore

final class HotKeyTests: XCTestCase {
    func testParsesModifiersAndKey() {
        XCTAssertEqual(HotKey.parse("cmd+shift+v"), HotKey(keyCode: 9, modifiers: HotKey.cmd | HotKey.shift))
        XCTAssertEqual(HotKey.parse("Option + Command + C"), HotKey(keyCode: 8, modifiers: HotKey.cmd | HotKey.option))
        XCTAssertEqual(HotKey.parse("ctrl+space"), HotKey(keyCode: 49, modifiers: HotKey.control))
    }

    func testRejectsInvalidShortcuts() {
        XCTAssertNil(HotKey.parse("v"))               // no modifier
        XCTAssertNil(HotKey.parse("cmd+shift"))       // no key
        XCTAssertNil(HotKey.parse("cmd+v+c"))         // two keys
        XCTAssertNil(HotKey.parse("cmd+f13"))         // unknown key
    }
}

final class AgentConfigTests: XCTestCase {
    func testDefaults() {
        let config = AgentConfig(environment: [:])
        XCTAssertEqual(config.apiURL.absoluteString, "http://127.0.0.1:5050")
        XCTAssertEqual(config.hotKey, .defaultHotKey)
        XCTAssertTrue(config.autoPaste)
        XCTAssertEqual(config.pollInterval, 0.5)
        XCTAssertTrue(config.ignoredApps.contains("com.1password.1password"))
    }

    func testEnvironmentOverrides() {
        let config = AgentConfig(environment: [
            "COPY_MEMORY_API": "http://localhost:9999",
            "COPY_MEMORY_HOTKEY": "cmd+option+v",
            "COPY_MEMORY_AUTO_PASTE": "0",
            "COPY_MEMORY_IGNORE_APPS": "com.foo.bar, com.baz",
            "COPY_MEMORY_POLL_INTERVAL": "0.01",
        ])
        XCTAssertEqual(config.apiURL.absoluteString, "http://localhost:9999")
        XCTAssertEqual(config.hotKey, HotKey(keyCode: 9, modifiers: HotKey.cmd | HotKey.option))
        XCTAssertFalse(config.autoPaste)
        XCTAssertTrue(config.ignoredApps.isSuperset(of: ["com.foo.bar", "com.baz"]))
        XCTAssertEqual(config.pollInterval, 0.1, "poll interval is clamped")
    }

    func testInvalidHotKeyFallsBackToDefault() {
        XCTAssertEqual(AgentConfig(environment: ["COPY_MEMORY_HOTKEY": "nonsense"]).hotKey, .defaultHotKey)
    }
}

final class SnapshotFilterTests: XCTestCase {
    let ignored = AgentConfig.defaultIgnoredApps

    func testConcealedAndTransientCopiesAreIgnored() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertTrue(SnapshotFilter.shouldIgnore(types: ["public.utf8-plain-text", marker], sourceBundleID: nil, ignoredApps: ignored))
        }
    }

    func testIgnoredAppsAndEmptyPasteboard() {
        XCTAssertTrue(SnapshotFilter.shouldIgnore(types: ["public.utf8-plain-text"], sourceBundleID: "com.bitwarden.desktop", ignoredApps: ignored))
        XCTAssertTrue(SnapshotFilter.shouldIgnore(types: [], sourceBundleID: nil, ignoredApps: ignored))
        XCTAssertFalse(SnapshotFilter.shouldIgnore(types: ["public.utf8-plain-text"], sourceBundleID: "com.apple.Safari", ignoredApps: ignored))
    }

    func testThumbnailOnlyForRealImages() {
        XCTAssertTrue(SnapshotFilter.wantsThumbnail(types: ["public.tiff", "public.png"]))
        XCTAssertFalse(SnapshotFilter.wantsThumbnail(types: ["public.file-url", "public.tiff"]))
        XCTAssertFalse(SnapshotFilter.wantsThumbnail(types: ["public.utf8-plain-text"]))
    }

    func testTotalBytes() {
        let s = Snapshot(items: [["a": Data(count: 3), "b": Data(count: 4)], ["c": Data(count: 5)]])
        XCTAssertEqual(s.totalBytes, 12)
    }
}

/// Serves canned responses and records requests, so the client can be tested without a server.
final class StubProtocol: URLProtocol {
    nonisolated(unsafe) static var handler: ((URLRequest) -> (Int, Data))?
    nonisolated(unsafe) static var requests: [URLRequest] = []

    override class func canInit(with request: URLRequest) -> Bool { true }
    override class func canonicalRequest(for request: URLRequest) -> URLRequest { request }

    override func startLoading() {
        var req = request
        if req.httpBody == nil, let stream = req.httpBodyStream {
            stream.open()
            var data = Data()
            var buffer = [UInt8](repeating: 0, count: 4096)
            while stream.hasBytesAvailable {
                let n = stream.read(&buffer, maxLength: buffer.count)
                if n <= 0 { break }
                data.append(buffer, count: n)
            }
            stream.close()
            req.httpBody = data
        }
        Self.requests.append(req)
        let (status, body) = Self.handler?(req) ?? (500, Data())
        let response = HTTPURLResponse(url: req.url!, statusCode: status, httpVersion: nil, headerFields: nil)!
        client?.urlProtocol(self, didReceive: response, cacheStoragePolicy: .notAllowed)
        client?.urlProtocol(self, didLoad: body)
        client?.urlProtocolDidFinishLoading(self)
    }

    override func stopLoading() {}
}

final class APIClientTests: XCTestCase {
    var client: APIClient!

    static let itemJSON = """
    {"id": 7, "kind": "text", "preview": "merhaba", "source_app": "com.apple.Notes", "source_app_name": "Notes",
     "types": ["public.utf8-plain-text"], "size": 7, "pinned": false, "copy_count": 1,
     "created_at": 1.0, "last_used_at": 2.0, "has_thumbnail": false}
    """

    override func setUp() {
        let config = URLSessionConfiguration.ephemeral
        config.protocolClasses = [StubProtocol.self]
        client = APIClient(baseURL: URL(string: "http://test.local")!, session: URLSession(configuration: config))
        StubProtocol.requests = []
    }

    func testAddSendsBase64Snapshot() async throws {
        StubProtocol.handler = { _ in (201, Data(Self.itemJSON.utf8)) }
        let snapshot = Snapshot(items: [["public.utf8-plain-text": Data("merhaba".utf8)]], sourceApp: "com.apple.Notes", sourceAppName: "Notes")
        let item = try await client.add(snapshot)
        XCTAssertEqual(item.id, 7)
        XCTAssertEqual(item.sourceAppName, "Notes")

        let req = try XCTUnwrap(StubProtocol.requests.first)
        XCTAssertEqual(req.httpMethod, "POST")
        XCTAssertEqual(req.url?.path, "/api/items")
        let body = try XCTUnwrap(JSONSerialization.jsonObject(with: req.httpBody ?? Data()) as? [String: Any])
        XCTAssertEqual(body["items"] as? [[String: String]], [["public.utf8-plain-text": "bWVyaGFiYQ=="]])
        XCTAssertEqual(body["source_app"] as? String, "com.apple.Notes")
        XCTAssertNil(body["thumbnail_png"])
    }

    func testListPassesQuery() async throws {
        StubProtocol.handler = { _ in (200, Data("{\"items\": [\(Self.itemJSON)], \"total\": 1}".utf8)) }
        let items = try await client.list(query: "şirket notu", limit: 20)
        XCTAssertEqual(items.map(\.preview), ["merhaba"])
        let url = try XCTUnwrap(StubProtocol.requests.first?.url)
        let query = URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems
        XCTAssertEqual(query?.first { $0.name == "q" }?.value, "şirket notu")
        XCTAssertEqual(query?.first { $0.name == "limit" }?.value, "20")
    }

    func testPayloadDecodesEveryRepresentation() async throws {
        StubProtocol.handler = { _ in (200, Data(#"{"items": [{"public.utf8-plain-text": "aGk=", "com.x": "AAE="}]}"#.utf8)) }
        let items = try await client.payload(id: 3)
        XCTAssertEqual(items, [["public.utf8-plain-text": Data("hi".utf8), "com.x": Data([0, 1])]])
    }

    func testHTTPErrorsAreSurfaced() async {
        StubProtocol.handler = { _ in (413, Data()) }
        do {
            try await client.add(Snapshot(items: [["a": Data()]]))
            XCTFail("expected error")
        } catch {
            XCTAssertEqual(error as? APIError, .status(413))
        }
    }

    func testPinAndDeleteUseCorrectVerbs() async throws {
        StubProtocol.handler = { req in (req.httpMethod == "DELETE" ? 204 : 200, Data(Self.itemJSON.utf8)) }
        try await client.setPinned(id: 4, pinned: true)
        try await client.delete(id: 4)
        XCTAssertEqual(StubProtocol.requests.map { "\($0.httpMethod!) \($0.url!.path)" },
                       ["PUT /api/items/4/pin", "DELETE /api/items/4"])
        XCTAssertEqual(client.thumbnailURL(id: 4).absoluteString, "http://test.local/api/items/4/thumbnail")
    }
}
