import Foundation

/// Everything that was on the pasteboard at one moment: one dictionary per
/// pasteboard item, mapping each UTI to its raw bytes.
public struct Snapshot: Equatable, Sendable {
    public var items: [[String: Data]]
    public var sourceApp: String?
    public var sourceAppName: String?
    public var thumbnailPNG: Data?

    public init(items: [[String: Data]], sourceApp: String? = nil, sourceAppName: String? = nil, thumbnailPNG: Data? = nil) {
        self.items = items
        self.sourceApp = sourceApp
        self.sourceAppName = sourceAppName
        self.thumbnailPNG = thumbnailPNG
    }

    public var totalBytes: Int { items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } } }

    func jsonObject() -> [String: Any] {
        var object: [String: Any] = [
            "items": items.map { $0.mapValues { $0.base64EncodedString() } },
        ]
        object["source_app"] = sourceApp
        object["source_app_name"] = sourceAppName
        object["thumbnail_png"] = thumbnailPNG?.base64EncodedString()
        return object
    }
}

public enum SnapshotFilter {
    /// Markers defined by nspasteboard.org that apps use to say "don't record this".
    public static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    public static let imageTypes: Set<String> = [
        "public.png", "public.tiff", "public.jpeg", "com.compuserve.gif", "public.heic", "com.adobe.pdf",
    ]

    public static func shouldIgnore(types: Set<String>, sourceBundleID: String?, ignoredApps: Set<String>) -> Bool {
        if types.isEmpty || !types.isDisjoint(with: markerTypes) { return true }
        if let id = sourceBundleID, ignoredApps.contains(id) { return true }
        return false
    }

    /// Thumbnails are only useful for real images, not for copied files.
    public static func wantsThumbnail(types: Set<String>) -> Bool {
        !types.isDisjoint(with: imageTypes) && !types.contains("public.file-url")
    }
}

public struct ClipItem: Decodable, Identifiable, Equatable, Sendable {
    public let id: Int
    public let kind: String
    public let preview: String
    public let sourceApp: String?
    public let sourceAppName: String?
    public let types: [String]
    public let size: Int
    public let pinned: Bool
    public let copyCount: Int
    public let createdAt: Double
    public let lastUsedAt: Double
    public let hasThumbnail: Bool
}
